def format_bytes(name, data):
    print(f"static const int {name}_SIZE = {len(data)};")
    print(f"static const uint8_t {name}[] = {{")
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        print(f"    {hex_str},")
    print("};")

