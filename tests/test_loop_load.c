// From jit_compiler_x86.cpp
static const uint8_t code_loop_load[] = {
    0x48, 0x8d, 0x0c, 0x06, 0x48, 0x89, 0x4c, 0x24, 0x08, 0x4c, 0x33, 0x01, 0x4c, 0x33, 0x49, 0x08,
    0x4c, 0x33, 0x51, 0x10, 0x4c, 0x33, 0x59, 0x18, 0x4c, 0x33, 0x61, 0x20, 0x4c, 0x33, 0x69, 0x28,
    0x4c, 0x33, 0x71, 0x30, 0x4c, 0x33, 0x79, 0x38, 0x48, 0x8d, 0x0c, 0x16, 0x48, 0x89, 0x4c, 0x24,
    0x10, 0xf3, 0x0f, 0xe6, 0x01, 0xf3, 0x0f, 0xe6, 0x49, 0x08, 0xf3, 0x0f, 0xe6, 0x51, 0x10, 0xf3,
    0x0f, 0xe6, 0x59, 0x18, 0xf3, 0x0f, 0xe6, 0x61, 0x20, 0xf3, 0x0f, 0xe6, 0x69, 0x28, 0xf3, 0x0f,
    0xe6, 0x71, 0x30, 0xf3, 0x0f, 0xe6, 0x79, 0x38, 0x41, 0x0f, 0x54, 0xe5, 0x41, 0x0f, 0x54, 0xed,
    0x41, 0x0f, 0x54, 0xf5, 0x41, 0x0f, 0x54, 0xfd, 0x41, 0x0f, 0x56, 0xe6, 0x41, 0x0f, 0x56, 0xee,
    0x41, 0x0f, 0x56, 0xf6, 0x41, 0x0f, 0x56, 0xfe,
};

int main(void) {
    printf("[TEST] Test loop_load buffer\n");

    // Allocate executable memory
    uint8_t *code = (uint8_t*)VirtualAlloc(NULL, 4096, MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
    if (!code) {
        printf("[FAIL] Code allocation\n");
        return 1;
    }

    // Clear with NOPs
    memset(code, 0x90, 4096);

    // Write prologue + loop_load + epilogue
    uint8_t* p = code;

    // Prologue: sub rsp, 0x20
    *p++ = 0x48; *p++ = 0x81; *p++ = 0xEC;
    *p++ = 0x20; *p++ = 0x00; *p++ = 0x00; *p++ = 0x00;

    // mov rax, rdi (just copy scratch)
    *p++ = 0x48; *p++ = 0x89; *p++ = 0xF8;

    // Copy loop_load
    memcpy(p, code_loop_load, sizeof(code_loop_load));
    p += sizeof(code_loop_load);

    // mov rax, rsi (just copy arg)
    *p++ = 0x48; *p++ = 0x89; *p++ = 0xF0;

    // Epilogue: add rsp, 0x20, ret
    *p++ = 0x48; *p++ = 0x81; *p++ = 0xC4;
    *p++ = 0x20; *p++ = 0x00; *p++ = 0x00; *p++ = 0x00;
    *p++ = 0xC3;

    printf("[TEST] Generated code at %p\n", code);

    // Try calling it with arguments
    typedef void (*LoopFunc)(uint8_t*, rx_memory_regs*);
    LoopFunc func = (LoopFunc)code;

    uint8_t scratchpad[256];
    memset(scratchpad, 0, sizeof(scratchpad));

    rx_memory_regs mr;
    mr.mx_ma = 0x1234567890ABCDEF;
    mr.memory = scratchpad;

    __try {
        printf("[TEST] Calling function with args...\n");
        func(scratchpad, &mr);
        printf("[TEST] Function returned OK\n");
    } __except(EXCEPTION_EXECUTE_HANDLER) {
        printf("[ERROR] Exception: 0x%08lx\n", GetExceptionCode());
    }

    VirtualFree(code, 0, MEM_RELEASE);
    return 0;
}

