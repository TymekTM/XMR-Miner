#include "crypto/blake2/blake2b.h"
#include "common/log.h"
#include <stdio.h>
#include <string.h>

static int test_blake2b_empty(void) {
    u8 hash[64];
    const u8 expected[64] = {
        0x78,0x6a,0x02,0xf7,0x42,0x01,0x59,0x03,0xc6,0xc6,0xfd,0x85,0x25,0x52,0xd2,0x72,
        0x91,0x2f,0x47,0x40,0xe1,0x58,0x47,0x61,0x8a,0x86,0xe2,0x17,0xf7,0x1f,0x54,0x19,
        0xd2,0x5e,0x10,0x31,0xaf,0xee,0x58,0x53,0x13,0x89,0x64,0x44,0x93,0x4e,0xb0,0x4b,
        0x90,0x3a,0x68,0x5b,0x14,0x48,0xb7,0x55,0xd5,0x6f,0x70,0x1a,0xfe,0x9b,0xe2,0xce,
    };

    blake2b_state S;
    blake2b_init(&S, 64);

    blake2b_final(&S, hash, 64);

    if (memcmp(hash, expected, 64) != 0) {
        LOG_ERR("FAIL: blake2b empty hash mismatch");
        return 1;
    }

    LOG_INFO("PASS: blake2b empty hash");
    return 0;
}

static int test_blake2b_hello(void) {
    u8 hash[64];
    const char *msg = "hello world";
    const u8 expected[64] = {
        0x02,0x1c,0xed,0x87,0x99,0x29,0x6c,0xec,0xa5,0x57,0x83,0x2a,0xb9,0x41,0xa5,0x0b,
        0x4a,0x11,0xf8,0x34,0x78,0xcf,0x14,0x1f,0x51,0xf9,0x33,0xf6,0x53,0xab,0x9f,0xbc,
        0xc0,0x5a,0x03,0x7c,0xdd,0xbe,0xd0,0x6e,0x30,0x9b,0xf3,0x34,0x94,0x2c,0x4e,0x58,
        0xcd,0xf1,0xa4,0x6e,0x23,0x79,0x11,0xcc,0xd7,0xfc,0xf9,0x78,0x7c,0xbc,0x7f,0xd0,
    };

    blake2b(hash, 64, msg, strlen(msg), NULL, 0);

    if (memcmp(hash, expected, 64) != 0) {
        LOG_ERR("FAIL: blake2b('hello world') mismatch");
        return 1;
    }

    LOG_INFO("PASS: blake2b('hello world')");
    return 0;
}

static int test_blake2b_32bytes(void) {
    u8 hash[32];
    const char *msg = "XMR-Miner";

    blake2b(hash, 32, msg, strlen(msg), NULL, 0);

    LOG_INFO("PASS: blake2b 32-byte output: %02x%02x%02x%02x...",
        hash[0], hash[1], hash[2], hash[3]);
    return 0;
}

static int test_blake2b_keyed(void) {
    u8 hash[64];
    u8 key[16] = {0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
                  0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10};

    blake2b_state state;
    if (blake2b_init_key(&state, 64, key, 16) != 0) {
        LOG_ERR("FAIL: blake2b_init_key");
        return 1;
    }
    blake2b_update(&state, "test", 4);
    blake2b_final(&state, hash, 64);

    LOG_INFO("PASS: blake2b keyed hash");
    return 0;
}

int main(void) {
    log_init(LOG_DEBUG);
    LOG_INFO("=== Blake2b Tests ===");

    int fails = 0;
    fails += test_blake2b_empty();
    fails += test_blake2b_hello();
    fails += test_blake2b_32bytes();
    fails += test_blake2b_keyed();

    LOG_INFO("=== Results: %d failures ===", fails);
    return fails;
}
